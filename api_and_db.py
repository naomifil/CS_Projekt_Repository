# inserts a location into the database and returns the created row.
# if the location already exists, the insert is ignored and the existing location is returned.
# Debugged with ChatGPT
def insert_locations(conn, coordinates):
    cursor = conn.cursor()
    location_ids = {}

    for lon, lat in coordinates:

        cursor.execute("""
            INSERT OR IGNORE INTO locations (name, latitude, longitude)
            VALUES (?, ?, ?)
        """, (f"{lat},{lon}", lat, lon))

        cursor.execute("""
            SELECT id FROM locations
            WHERE latitude = ? AND longitude = ?
        """, (lat, lon))

        row = cursor.fetchone()
        if row:
            location_ids[(lon, lat)] = row[0]

    return location_ids

# Inserts a list of stations into the database
# Generated by ChatGPT
def insert_stations(conn, station_map, location_ids):
    cursor = conn.cursor()

    for key, stations in station_map.items():
        lon, lat = map(float, key.split(","))
        location_id = location_ids[(lon, lat)]

        for station in stations:
            cursor.execute("""
                INSERT OR IGNORE INTO stations (
                    location_id, station_api_id, name
                )
                VALUES (?, ?, ?)
            """, (
                location_id,
                station["id"],
                station["name"],
            ))

# extracts air quality measurement information from station readings and inserts them into the db
# generated by ChatGPT
def insert_air_quality_measurements(conn, results, location_ids):
    cursor = conn.cursor()

    for entry in results:
        lon, lat = entry.coordinate
        agg = entry

        readings = agg.readings
        station_count = agg.station_count

        location_id = location_ids[(lon, lat)]

        pm25 = readings.get("pm25")
        pm10 = readings.get("pm10")
        o3 = readings.get("o3")

        # helper functions to extract the correct properties
        def val(x): return x.value if x else None
        def unit(x): return x.units if x else None

        timestamp = datetime.now(timezone.utc).isoformat()

        cursor.execute("""
            INSERT OR IGNORE INTO air_quality (
                location_id,
                pm25, pm10, o3,
                units_pm25, units_pm10, units_o3,
                station_count,
                timestamp
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            location_id,
            val(pm25), val(pm10), val(o3),
            unit(pm25), unit(pm10), unit(o3),
            station_count,
            timestamp,
        ))

def insert_weather_measurements(conn, weather_results, location_ids):
    cursor = conn.cursor()

    for (lon, lat), data in zip(location_ids.keys(), weather_results.values()):
        location_id = location_ids[(lon, lat)]

        # daily forecast/history
        daily_df = data["daily"]

        for _, row in daily_df.iterrows():
            cursor.execute("""
                INSERT OR IGNORE INTO weather_daily (
                    location_id,
                    date,
                    temperature_mean,
                    relative_humidity_mean
                )
                VALUES (?, ?, ?, ?)
            """, (
                location_id,
                row["date"].strftime("%Y-%m-%d %H:%M:%S"),
                row["temperature_mean"],
                row["relative_humidity_mean"],
            ))

